/*
 * pidfd_open/getfd are 434/438 on the generic Linux syscall ABI
 * (x86_64, i386, aarch64, arm, riscv, loongarch). Do not guess
 * those numbers elsewhere -- MIPS/Alpha/etc. use different
 * numbering, and a wrong syscall is worse than failing the steal.
 */
#if defined(__linux__)
#include <sys/syscall.h>
#if !defined(__NR_pidfd_open) || !defined(__NR_pidfd_getfd)
#if defined(__x86_64__) || defined(__i386__) || defined(__aarch64__) || \
    defined(__arm__) || defined(__riscv) || defined(__loongarch__)
#ifndef	__NR_pidfd_open
#define	__NR_pidfd_open	434
#endif
#ifndef	__NR_pidfd_getfd
#define	__NR_pidfd_getfd	438
#endif
#ifndef	__NR_pidfd_send_signal
#define	__NR_pidfd_send_signal	424
#endif
#endif
#endif
#ifndef	__NR_pidfd_send_signal
#if defined(__x86_64__) || defined(__i386__) || defined(__aarch64__) || \
    defined(__arm__) || defined(__riscv) || defined(__loongarch__)
#define	__NR_pidfd_send_signal	424
#endif
#endif
#ifndef	__NR_close_range
#if defined(__x86_64__) || defined(__i386__) || defined(__aarch64__) || \
    defined(__arm__) || defined(__riscv) || defined(__loongarch__)
#define	__NR_close_range	436
#endif
#endif
#endif /* __linux__ */

